/**
 * Plugin only reads WooCommerce's own product sales totals.
 * This is quantity sold, not number of customers or unique purchases.
 */
function mucmay_sales_markup( $product, $context = 'catalog' ) {
    if ( ! is_object( $product ) || ! method_exists( $product, 'get_total_sales' ) ) {
        return '';
    }

    $units = max( 0, (int) $product->get_total_sales() );
    $class = 'mm-sales-count';
    if ( 'single' === $context ) {
        $class .= ' mm-sales-count--single';
    } elseif ( 'home' === $context ) {
        $class .= ' mm-sales-count--home';
    }
    $label = sprintf(
        /* translators: %s is the total number of units sold. */
        __( 'Đã bán %s', 'muc-may-sales' ),
        number_format_i18n( $units )
    );

    return '<span class="' . esc_attr( $class ) . '" aria-label="' . esc_attr( $label ) . '">' .
        '<span class="mm-sales-count__mark" aria-hidden="true">✳</span>' .
        '<span>' . esc_html__( 'ĐÃ BÁN', 'muc-may-sales' ) . '</span>' .
        '<strong>' . esc_html( number_format_i18n( $units ) ) . '</strong>' .
        '</span>';
}

/**
 * Mực Mây's custom homepage cards call get_price_html() directly and do not
 * run the standard WooCommerce loop actions. Append the label there only.
 */
function mucmay_sales_home_price( $html, $product ) {
    if ( is_admin() || wp_doing_ajax() || ! function_exists( 'is_front_page' ) || ! is_front_page() ) {
        return $html;
    }
    return $html . mucmay_sales_markup( $product, 'home' );
}

/** Standard WooCommerce archive and single-product hooks. */
function mucmay_sales_loop_note() {
    global $product;
    echo mucmay_sales_markup( $product ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by the escaped markup helper.
}
function mucmay_sales_single_note() {
    global $product;
    echo mucmay_sales_markup( $product, 'single' ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Generated by the escaped markup helper.
}

function mucmay_sales_assets() {
    if ( is_admin() ) {
        return;
    }
    if ( function_exists( 'is_front_page' ) && is_front_page() ||
        function_exists( 'is_shop' ) && is_shop() ||
        function_exists( 'is_product' ) && is_product() ||
        function_exists( 'is_product_category' ) && is_product_category() ||
        function_exists( 'is_product_tag' ) && is_product_tag() ) {
        wp_enqueue_style( 'mucmay-sales', plugins_url( 'assets/sales.css', MUC_MAY_SALES_PLUGIN_FILE ), array(), MUC_MAY_SALES_VERSION );
    }
}

/**
 * A clear "sort by sales" option in the native WooCommerce catalog dropdown.
 * The native `popularity` sort already uses WooCommerce sales totals via the
 * product lookup table, so avoid implementing a second potentially slower SQL
 * query or a meta query which might omit products with zero sales.
 */
function mucmay_sales_sorting_options( $options ) {
    if ( ! is_array( $options ) ) {
        return $options;
    }
    // Show this prominently, including stores where sorting was customized.
    $sales_label = __( 'Bán chạy nhất (theo lượt bán)', 'muc-may-sales' );
    $result = array();
    foreach ( $options as $key => $label ) {
        $result[ $key ] = $label;
        if ( 'menu_order' === $key ) {
            $result['popularity'] = $sales_label;
        }
    }
    $result['popularity'] = $sales_label;
    return $result;
}

/** Explicitly expose sales count in the WP Admin products table. */
function mucmay_sales_product_column( $columns ) {
    $columns['mucmay_sales_total'] = __( 'Đã bán', 'muc-may-sales' );
    return $columns;
}

function mucmay_sales_product_column_value( $column, $product_id ) {
    if ( 'mucmay_sales_total' !== $column || ! function_exists( 'wc_get_product' ) ) {
        return;
    }
    $product = wc_get_product( $product_id );
    echo esc_html( number_format_i18n( $product ? max( 0, (int) $product->get_total_sales() ) : 0 ) );
}

/** Disable stale-looking badges when cached pages load an older stylesheet. */
function mucmay_sales_admin_plugin_notice() {
    if ( ! current_user_can( 'manage_woocommerce' ) ) {
        return;
    }
    // Only show on our own statistics page.
    if ( ! isset( $_GET['page'] ) || 'mucmay-sales' !== sanitize_key( wp_unslash( $_GET['page'] ) ) ) { // phpcs:ignore WordPress.Security.NonceVerification.Recommended
        return;
    }
    echo '<div class="notice notice-info"><p><strong>Mực Mây v' . esc_html( MUC_MAY_SALES_VERSION ) . '</strong>: ' .
        esc_html__( 'Lượt bán lấy từ dữ liệu WooCommerce (đơn đã thanh toán), bao gồm cả số 0. Nếu ngoài cửa hàng chưa hiện, hãy xóa cache LiteSpeed/CDN và kiểm tra plugin đang Kích hoạt.', 'muc-may-sales' ) . '</p></div>';
}

function mucmay_sales_admin_page() {
    if ( ! current_user_can( 'manage_woocommerce' ) ) {
        wp_die( esc_html__( 'Bạn không có quyền xem thống kê.', 'muc-may-sales' ) );
    }
    if ( ! function_exists( 'wc_get_orders' ) || ! function_exists( 'wc_get_products' ) ) {
        echo '<div class="wrap"><h1>Mực Mây · Thống kê</h1><p>Vui lòng kích hoạt WooCommerce.</p></div>';
        return;
    }

    $paid_statuses = function_exists( 'wc_get_is_paid_statuses' ) ? wc_get_is_paid_statuses() : array( 'processing', 'completed' );
    $count_result  = wc_get_orders( array(
        'status'   => $paid_statuses,
        'type'     => 'shop_order',
        'limit'    => 1,
        'paginate' => true,
        'return'   => 'ids',
    ) );
    $paid_orders = is_object( $count_result ) && isset( $count_result->total ) ? (int) $count_result->total : 0;

    // Small WooCommerce storefront: calculated on demand only in admin.
    // Products and orders remain the source of truth; no counters are stored.
    $products = wc_get_products( array( 'status' => 'publish', 'limit' => -1 ) );
    $active_products = 0;
    $sold_units = 0;
    $ranking = array();
    foreach ( $products as $item ) {
        if ( ! is_object( $item ) || ! method_exists( $item, 'get_total_sales' ) ) {
            continue;
        }
        $active_products++;
        $qty = max( 0, (int) $item->get_total_sales() );
        $sold_units += $qty;
        $ranking[] = array( 'product' => $item, 'qty' => $qty );
    }
    usort( $ranking, static function ( $a, $b ) { return $b['qty'] <=> $a['qty']; } );
    $ranking = array_slice( $ranking, 0, 5 );

    $orders_link   = admin_url( 'admin.php?page=wc-orders' );
    $products_link = admin_url( 'edit.php?post_type=product' );
    $analytics_link = admin_url( 'admin.php?page=wc-admin&path=%2Fanalytics%2Foverview' );
    ?>
    <div class="wrap mm-sales-admin">
      <div class="mm-sales-admin__heading">
        <div>
          <p class="mm-sales-admin__eyebrow">MỰC MÂY STUDIO / SỔ THEO DÕI</p>
          <h1>Chuyện mua &amp; bán <em>của tiệm.</em></h1>
          <p>Một góc nhìn nhanh về các đơn đã thanh toán và những món đồ đã bán.</p>
        </div>
        <span class="mm-sales-admin__stamp" aria-hidden="true">MỰC<br>MÂY ✳</span>
      </div>
      <div class="mm-sales-admin__stats">
        <div class="mm-sales-admin__stat"><span>01 / ĐƠN ĐÃ THANH TOÁN</span><strong><?php echo esc_html( number_format_i18n( $paid_orders ) ); ?></strong><small>Đơn ở trạng thái đã thanh toán</small></div>
        <div class="mm-sales-admin__stat"><span>02 / SẢN PHẨM ĐÃ BÁN</span><strong><?php echo esc_html( number_format_i18n( $sold_units ) ); ?></strong><small>Tổng số lượng bán của sản phẩm đang hiển thị</small></div>
        <div class="mm-sales-admin__stat"><span>03 / MẶT HÀNG TRÊN KỆ</span><strong><?php echo esc_html( number_format_i18n( $active_products ) ); ?></strong><small>Sản phẩm đã xuất bản</small></div>
      </div>
      <div class="mm-sales-admin__section">
        <div class="mm-sales-admin__section-head">
          <div><span>GHI CHÚ #01</span><h2>Những món được yêu thích</h2></div>
          <a href="<?php echo esc_url( $products_link ); ?>">Quản lý sản phẩm &rarr;</a>
        </div>
        <table class="widefat fixed striped mm-sales-admin__table">
          <thead><tr><th>Sản phẩm</th><th>Đã bán (số lượng)</th></tr></thead>
          <tbody>
          <?php if ( empty( $ranking ) ) : ?>
            <tr><td colspan="2">Cửa tiệm chưa có sản phẩm được xuất bản.</td></tr>
          <?php else : foreach ( $ranking as $row ) :
              $item = $row['product']; ?>
            <tr>
              <td>
                <span class="mm-sales-admin__product">
                  <?php echo wp_kses_post( $item->get_image( array( 46, 46 ) ) ); ?>
                  <a href="<?php echo esc_url( get_edit_post_link( $item->get_id() ) ?: get_permalink( $item->get_id() ) ); ?>"><?php echo esc_html( $item->get_name() ); ?></a>
                </span>
              </td>
              <td><strong><?php echo esc_html( number_format_i18n( $row['qty'] ) ); ?></strong></td>
            </tr>
          <?php endforeach; endif; ?>
          </tbody>
        </table>
      </div>
      <div class="mm-sales-admin__foot">
        <p><strong>Đọc đúng số liệu:</strong> “Đơn đã thanh toán” đếm số đơn ở trạng thái WooCommerce coi là đã trả tiền; “Sản phẩm đã bán” là số lượng sản phẩm, không phải số khách mua. Đơn đang chờ thanh toán không được tính vào số đơn đã thanh toán.</p>
        <div class="mm-sales-admin__links"><a href="<?php echo esc_url( add_query_arg( 'orderby', 'popularity', wc_get_page_permalink( 'shop' ) ) ); ?>">Xem cửa hàng theo lượt bán &rarr;</a><a href="<?php echo esc_url( $orders_link ); ?>">Xem đơn hàng &rarr;</a><a href="<?php echo esc_url( $analytics_link ); ?>">WooCommerce Analytics &rarr;</a></div>
      </div>
    </div>
    <?php
}

function mucmay_sales_bootstrap() {
    if ( ! class_exists( 'WooCommerce' ) ) {
        return;
    }

    add_filter( 'woocommerce_get_price_html', 'mucmay_sales_home_price', 99, 2 );

    // Re-label WooCommerce's existing best-selling ordering mode. It sorts by
    // WC's total_sales field and remains available even when there are 0 sales.
    add_filter( 'woocommerce_catalog_orderby', 'mucmay_sales_sorting_options', 25 );
    add_filter( 'woocommerce_default_catalog_orderby_options', 'mucmay_sales_sorting_options', 25 );
    add_action( 'woocommerce_after_shop_loop_item_title', 'mucmay_sales_loop_note', 12 );
    add_action( 'woocommerce_single_product_summary', 'mucmay_sales_single_note', 12 );
    add_filter( 'manage_edit-product_columns', 'mucmay_sales_product_column', 30 );
    add_action( 'manage_product_posts_custom_column', 'mucmay_sales_product_column_value', 10, 2 );
    add_action( 'admin_notices', 'mucmay_sales_admin_plugin_notice' );
    add_action( 'wp_enqueue_scripts', 'mucmay_sales_assets', 30 );

    add_action( 'admin_menu', static function () {
        add_submenu_page( 'woocommerce', 'Mực Mây · Thống kê', 'Mực Mây · Thống kê', 'manage_woocommerce', 'mucmay-sales', 'mucmay_sales_admin_page' );
    } );
    add_action( 'admin_enqueue_scripts', static function ( $hook ) {
        if ( $hook === 'woocommerce_page_mucmay-sales' ) {
            wp_enqueue_style( 'mucmay-sales-admin', plugins_url( 'assets/sales.css', MUC_MAY_SALES_PLUGIN_FILE ), array(), MUC_MAY_SALES_VERSION );
        }
    } );
}
add_action( 'plugins_loaded', 'mucmay_sales_bootstrap', 20 );
